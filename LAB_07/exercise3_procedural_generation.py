def main():
    print("=== EX3 Typical Examples ===")

    # Typical example from the question:
    # 1024-pixel line, depth = 10
    n_midpoints = count_midpoints(10)
    print("For a 1024-pixel line with depth 10 -> number of midpoints =", n_midpoints)

    # roughness discussion
    print("If roughness = 0 -> result is smooth and regular")
    print("If roughness = 2 -> result is more irregular and rough")

    # edge-case tests
    run_edge_case_tests()

    # ---------- Turtle setup ----------
    screen = turtle.Screen()
    screen.setup(width=1400, height=850)
    screen.bgcolor("white")
    screen.title("Exercise 3 - Recursive Patterns")
    screen.tracer(0)

    t = turtle.Turtle()
    t.hideturtle()
    t.speed(0)
    t.pensize(2)

    # ---------- Typical example 1: midpoint displacement ----------
    # 1024-pixel line, depth = 10
    t.color("black")
    points = midpoint_displacement(-620, 250, 404, 250, roughness=20, depth=10)
    draw_polyline(t, points)

    # ---------- Typical example 2: terrain ----------
    # start with 4 corners at height 0
    terrain = generate_terrain(33, 33, roughness=12, depth=5)
    draw_terrain(t, terrain, start_x=120, start_y=-260, cell_size=10)

    # ---------- Typical example 3: artifacts ----------
    artifacts = detect_artifacts(terrain, threshold=15)
    print("Detected suspicious coordinates in terrain:", len(artifacts))
    draw_artifacts(t, artifacts, start_x=120, start_y=-260, cell_size=10)

    screen.update()
    turtle.done()


if __name__ == "__main__":
    main()