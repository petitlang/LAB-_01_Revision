# 5. Edge Case Tests
# =========================

def run_edge_case_tests():
    print("\n=== EX3 Edge Case Tests ===")

    # ---- midpoint_displacement ----
    print("\n1. midpoint_displacement")
    p0 = midpoint_displacement(0, 0, 100, 0, 1, 0)
    print("Edge Case: depth = 0")
    print("Actual result:", p0)

    p1 = midpoint_displacement(0, 0, 100, 0, 0, 4)
    print("Edge Case: roughness = 0")
    print("Actual result: generated", len(p1), "points on a smooth line")

    try:
        midpoint_displacement(0, 0, 100, 0, 1, -1)
    except Exception as e:
        print("Edge Case: negative depth")
        print("Actual result:", e)

    # ---- generate_terrain ----
    print("\n2. generate_terrain")
    terrain0 = generate_terrain(9, 9, 1, 0)
    print("Edge Case: depth = 0")
    print("Actual result: terrain shape =", terrain0.shape)

    terrain1 = generate_terrain(9, 9, 0, 3)
    print("Edge Case: roughness = 0")
    print("Actual result: smoother terrain generated")

    try:
        generate_terrain(0, 9, 1, 2)
    except Exception as e:
        print("Edge Case: invalid grid size")
        print("Actual result:", e)

    # ---- detect_artifacts ----
    print("\n3. detect_artifacts")
    simple = np.array([[0, 1], [2, 3]], dtype=float)

    a0 = detect_artifacts(simple, 0)
    print("Edge Case: threshold = 0")
    print("Actual result: suspicious coordinates =", a0)

    a1 = detect_artifacts(simple, 1000)
    print("Edge Case: very large threshold")
    print("Actual result: suspicious coordinates =", a1)

    try:
        detect_artifacts(simple, -1)
    except Exception as e:
        print("Edge Case: negative threshold")
        print("Actual result:", e)


